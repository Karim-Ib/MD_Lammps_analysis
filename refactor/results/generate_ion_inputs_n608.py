"""Generate N net-neutral 608-water LAMMPS input configurations.

Each config is a freshly generated liquid-water box (ambient density) with
exactly one OH- / H3O+ pair seeded via a Grotthuss-style H displacement, so
the *whole system* is charge-neutral (net charge 0). Output is one
``atom_style atomic`` ``.data`` file per run plus a ``manifest.json``
recording every seed for full reproducibility.

Seeding strategy (why the runs are not identical):
    A single master SeedSequence is spawned into one child per run; each
    child is spawned again into an independent (box, ion) pair. SeedSequence
    spawning yields decorrelated streams and, unlike ``master + i``, avoids
    accidental correlations. Recording the master seed + run index lets any
    box be regenerated byte-for-byte.

Usage:
    python -m results.generate_ion_inputs_n608 --out-dir <DIR> [--n-runs 10]
"""
from __future__ import annotations

import argparse
import json
import platform
from datetime import datetime
from pathlib import Path

import numpy as np

from mdwater import constants
from mdwater.constants import water_density_to_number_density
from mdwater.ions import assign_hydrogen_to_oxygen, displace_hydrogen_to_neighbour
from mdwater.ions.tracker import identify_ions
from mdwater.io.writers import write_lammps_data_snapshot
from mdwater.pbc import minimum_image
from mdwater.water_box import WaterBoxSpec, generate_water_box
from mdwater.water_box.generator import intermolecular_contacts

N_MOLECULES = 608
MASTER_SEED = 20250720          # recorded in manifest; change to reroll the batch
TARGET_OO = 2.8                 # donor-acceptor O-O distance for the seeded pair (A)
OO_EPS = 0.2                    # tolerance on TARGET_OO
MIN_OO = 2.4                    # hard-core O-O separation in the neutral box (A)
H_TYPE, O_TYPE = 1, 2           # LAMMPS atom types (masses [M_H, M_O])


def build_atoms_array(H_pos: np.ndarray, O_pos: np.ndarray) -> np.ndarray:
    """Assemble an (N, 5) [id, type, x, y, z] array: H atoms then O atoms."""
    n_h, n_o = H_pos.shape[0], O_pos.shape[0]
    atoms = np.zeros((n_h + n_o, 5), dtype=float)
    atoms[:n_h, 0] = np.arange(1, n_h + 1)
    atoms[:n_h, 1] = H_TYPE
    atoms[:n_h, 2:5] = H_pos
    atoms[n_h:, 0] = np.arange(n_h + 1, n_h + n_o + 1)
    atoms[n_h:, 1] = O_TYPE
    atoms[n_h:, 2:5] = O_pos
    return atoms


def generate_one(box_seed: np.random.SeedSequence,
                 ion_seed: np.random.SeedSequence,
                 density_g_per_cm3: float = constants.WATER_DENSITY_G_PER_CM3,
                 ) -> tuple[np.ndarray, np.ndarray, dict]:
    """Return (atoms[N,5], box_edges[3], info) for one net-neutral config.

    ``density_g_per_cm3`` defaults to the literature ambient value in
    ``constants``. It is deliberately *not* taken from any existing trajectory:
    the pilot run `neutral_run_0` sits at ~0.898 g/cm3, and matching that would
    bake a pilot artefact into every new input. Configs generated here are
    therefore at a different state point from `neutral_run_0` and must not be
    pooled with it.
    """
    number_density = water_density_to_number_density(density_g_per_cm3)
    wb = generate_water_box(WaterBoxSpec(
        n_molecules=N_MOLECULES,
        number_density=number_density,
        min_OO=MIN_OO,
        seed=box_seed,
    ))
    box = wb.box
    H, O = wb.H_positions.copy(), wb.O_positions

    h_to_o = assign_hydrogen_to_oxygen(H, O, box)
    result = displace_hydrogen_to_neighbour(
        hydrogen_pos=H, oxygen_pos=O, hydrogen_to_oxygen=h_to_o, box=box,
        target_oo_distance=TARGET_OO, eps=OO_EPS,
        rng=np.random.default_rng(ion_seed),
    )
    H[result.moved_h_idx] = result.new_h_position

    # Verify the whole system is one OH- + one H3O+ (net neutral) before writing.
    frame = identify_ions(H, O, box)
    if frame.oh_indices.size != 1 or frame.h3o_indices.size != 1:
        raise RuntimeError(
            f"expected exactly 1 OH- and 1 H3O+, got "
            f"{frame.oh_indices.size} OH- / {frame.h3o_indices.size} H3O+"
        )

    # Record the geometry actually produced, so a bad seed is visible in the
    # manifest rather than only showing up as an exploding MD run. Ownership is
    # re-derived *after* the proton move, otherwise the hydronium's new covalent
    # O-H bond is scored as an intermolecular contact.
    owner_after = assign_hydrogen_to_oxygen(H, O, box)
    hh, ho = intermolecular_contacts(H, O, box, owner=owner_after)
    acc_h = H[owner_after == result.acceptor_o_idx]
    v = minimum_image(acc_h - O[result.acceptor_o_idx], box)
    v /= np.linalg.norm(v, axis=1, keepdims=True)
    angles = [float(np.degrees(np.arccos(np.clip(v[a] @ v[b], -1, 1))))
              for a in range(len(v)) for b in range(a + 1, len(v))]

    atoms = build_atoms_array(H, O)
    info = {
        "donor_o_idx": result.donor_o_idx,
        "acceptor_o_idx": result.acceptor_o_idx,
        "moved_h_idx": result.moved_h_idx,
        "oo_distance": round(result.oo_distance, 4),
        "box_length": round(float(box[0]), 4),
        "density_g_per_cm3": round(density_g_per_cm3, 6),
        "n_atoms": int(atoms.shape[0]),
        "closest_HH_angstrom": round(hh, 4),
        "closest_HO_angstrom": round(ho, 4),
        "h3o_hoh_angles_deg": [round(a, 2) for a in angles],
    }
    return atoms, box, info


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-dir", required=True, type=Path)
    ap.add_argument("--n-runs", type=int, default=10)
    ap.add_argument("--master-seed", type=int, default=MASTER_SEED)
    ap.add_argument("--density", type=float,
                    default=constants.WATER_DENSITY_G_PER_CM3,
                    help="mass density in g/cm3 (default: literature ambient "
                         f"{constants.WATER_DENSITY_G_PER_CM3}). Not taken from "
                         "any existing run -- see generate_one().")
    args = ap.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)

    master = np.random.SeedSequence(args.master_seed)
    children = master.spawn(args.n_runs)

    manifest = {
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "host": platform.node(),
        "n_molecules": N_MOLECULES,
        "n_runs": args.n_runs,
        "master_seed": args.master_seed,
        "number_density_per_A3": round(water_density_to_number_density(args.density), 6),
        "water_density_g_per_cm3": args.density,
        "density_source": ("literature (constants.WATER_DENSITY_G_PER_CM3)"
                           if args.density == constants.WATER_DENSITY_G_PER_CM3
                           else "user override via --density"),
        "target_oo_distance": TARGET_OO,
        "oo_eps": OO_EPS,
        "min_OO": MIN_OO,
        "atom_types": {"1": "H", "2": "O"},
        "runs": [],
    }

    masses = [constants.M_H, constants.M_O]
    for i, child in enumerate(children):
        box_seed, ion_seed = child.spawn(2)
        atoms, box, info = generate_one(box_seed, ion_seed, args.density)
        fname = f"n608_ionpair_{i:02d}.data"
        box_lohi = np.column_stack([np.zeros(3), box])
        write_lammps_data_snapshot(args.out_dir / fname, atoms, box_lohi, masses)
        info.update({
            "index": i,
            "file": fname,
            "box_seed_entropy": list(box_seed.entropy) if hasattr(box_seed.entropy, "__iter__") else box_seed.entropy,
            "box_seed_spawn_key": list(box_seed.spawn_key),
        })
        manifest["runs"].append(info)
        print(f"[{i:02d}] {fname}  L={info['box_length']} A  "
              f"OH-@{info['donor_o_idx']} H3O+@{info['acceptor_o_idx']}  "
              f"dOO={info['oo_distance']} A  "
              f"HOH={'/'.join(f'{a:.0f}' for a in info['h3o_hoh_angles_deg'])} deg  "
              f"minHH={info['closest_HH_angstrom']:.2f} A")

    with (args.out_dir / "manifest.json").open("w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
    print(f"\nWrote {args.n_runs} configs + manifest.json to {args.out_dir}")


if __name__ == "__main__":
    main()
